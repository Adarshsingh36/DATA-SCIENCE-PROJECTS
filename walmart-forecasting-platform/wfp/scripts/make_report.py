"""Generate docs/results.md and report figures from saved pipeline artifacts (no numbers are typed by hand)."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from walmartfc.dashboard.figures import MODEL_LABEL
from walmartfc.dashboard.data import Store

RES, FIG = ROOT / "reports/results", ROOT / "reports/figures"
LEVELS = ["total", "group", "store", "dept", "store_dept"]
LBL = lambda m: MODEL_LABEL.get(m, m)  # noqa: E731


def md(df: pd.DataFrame, pct=(), nd=3) -> str:
    d = df.copy()
    for c in d.columns:
        if c in pct:
            d[c] = (d[c] * 100).map(lambda x: f"{x:.2f}%")
        elif d[c].dtype.kind == "f":
            d[c] = d[c].map(lambda x: f"{x:,.{nd}f}" if abs(x) < 100 else f"{x:,.0f}")
    cols = list(d.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    out += ["| " + " | ".join(str(v) for v in r) + " |" for r in d.itertuples(index=False)]
    return "\n".join(out)


def main():
    st = Store()
    out = ["# Results (auto-generated by `scripts/make_report.py`)", "",
           "All numbers are out-of-sample: every model is trained on weeks strictly before the test window; the 13 weeks "
           "before the test window are used only for early stopping, interval calibration and method selection.", ""]
    sel = {f: st.selected(f) for f in st.folds}
    for fold in st.folds:
        info = json.loads((ROOT / "artifacts" / f"fold_{fold}" / "info.json").read_text())
        dts = st.test_dates(fold)
        m = st.metrics(fold)
        out += [f"## Fold `{fold}`: test weeks {dts[0].date()} to {dts[-1].date()}", "",
                f"Validation-selected reconciliation: **{LBL(info['selected_reconciliation'])}** (validation error only); operational default used downstream: **{LBL(sel[fold])}**. "
                f"Validation WAPE by method: " + ", ".join(f"{k}={v:.3%}" for k, v in info['val_reconciliation_wape'].items()), "",
                "### Bottom level (Store x Department), 13-week horizon", ""]
        t = m[m.level == "store_dept"].copy(); t["model"] = t.model.map(LBL)
        out += [md(t[["model", "WAPE", "RMSSE", "RMSSE_w", "MAE", "RMSE", "Bias", "n_obs"]].sort_values("WAPE"), pct=("WAPE", "Bias")), ""]
        out += ["### WAPE by hierarchy level", ""]
        p = m[m.level.isin(LEVELS)].pivot_table(index="model", columns="level", values="WAPE")[LEVELS]
        p.index = [LBL(i) for i in p.index]; p.columns = [c.replace("store_dept", "store x dept") for c in p.columns]
        out += [md(p.reset_index().rename(columns={"index": "model"}), pct=tuple(p.columns)), ""]
        im = st.interval_metrics(fold)
        im = im[im.level.isin(["store_dept", "total"])].copy(); im["model"] = im.model.map(LBL)
        out += ["### 80% prediction intervals (nominal coverage 80%)", "",
                md(im[["model", "level", "interval", "coverage", "rel_width", "interval_score"]], pct=("coverage", "rel_width")), ""]
        out += [f"Base forecast incoherence before reconciliation (max |aggregate - sum of children|, $): "
                f"{info['coherence']['base_unreconciled']:,.0f}; after reconciliation: "
                f"{max(v for k, v in info['coherence'].items() if k != 'base_unreconciled'):.1e}", ""]
    rep = st.rep_metrics()
    if rep is not None:
        out += ["## Representative subset: all models on identical series (incl. Prophet and Temporal Fusion Transformer)", ""]
        r = rep.copy(); r["model"] = r.model.map(LBL)
        out += [md(r[["fold", "model", "n_series", "WAPE", "RMSSE", "RMSSE_w", "MAE", "RMSE", "Bias"]], pct=("WAPE", "Bias")), ""]
        ri = st.rep_intervals()
        if ri is not None:
            ri = ri.copy(); ri["model"] = ri.model.map(LBL)
            out += ["Interval quality on the subset:", "", md(ri[["fold", "model", "coverage", "rel_width", "interval_score"]],
                                                              pct=("coverage", "rel_width")), ""]
    s = st.inventory_summary()
    if s is not None:
        out += ["## Inventory optimisation (scenario assumptions; realised sales used as demand)", "",
                md(s.rename(columns={"policy": "policy"}), nd=2), "",
                "Costs are in dollars under the assumed cost parameters in `config/default.yaml`; they illustrate the optimiser, "
                "they are not claims about Walmart's actual economics.", ""]
    (ROOT / "docs/results.md").write_text("\n".join(out))

    # ---- figures -------------------------------------------------------------------------------------------
    FIG.mkdir(parents=True, exist_ok=True)
    fold = st.folds[-1]
    m = st.metrics(fold)
    h = m[m.level.str.startswith("store_dept@h")].copy(); h["h"] = h.level.str.extract(r"@h(\d+)").astype(int)
    fig, ax = plt.subplots(figsize=(8, 4))
    for mod in ["naive", "snaive", "lgbm", sel[fold]]:
        g = h[h.model == mod].sort_values("h"); ax.plot(g.h, g.WAPE * 100, marker="o", label=LBL(mod))
    ax.set_xlabel("weeks ahead"); ax.set_ylabel("WAPE %"); ax.legend(); ax.set_title(f"Store x Dept WAPE by horizon ({fold} fold)")
    fig.tight_layout(); fig.savefig(FIG / "06_horizon_wape.png", dpi=140); plt.close(fig)

    fi = pd.read_csv(ROOT / "artifacts" / f"fold_{fold}" / "feature_importance.csv").head(15).iloc[::-1]
    fig, ax = plt.subplots(figsize=(7, 5)); ax.barh(fi.feature, fi.gain_share * 100, color="#1f4e79")
    ax.set_xlabel("share of total gain %"); ax.set_title("LightGBM feature importance (point model)")
    fig.tight_layout(); fig.savefig(FIG / "07_feature_importance.png", dpi=140); plt.close(fig)

    for tag, node in (("total", 0), ("store", st.node_options("store")[0]["value"])):
        f = st.forecasts(fold); d = f[(f.model == sel[fold]) & (f.node == node)].sort_values("h")
        hist = st.history(node); td = st.test_dates(fold)
        fig, ax = plt.subplots(figsize=(9, 4)); ax.plot(hist.index[-60:], hist.values[-60:], color="#555", label="actual")
        ax.plot(td[d.h.to_numpy() - 1], d.y_hat, color="#1f4e79", lw=2.5, label=LBL(sel[fold]))
        ax.fill_between(td[d.h.to_numpy() - 1], d.lo, d.hi, color="#1f4e79", alpha=.2, label="80% interval")
        ax.axvline(td[0], color="red", ls=":"); ax.legend(); ax.set_title(f"{st.rows.name[node]}: forecast vs actual ({fold})")
        fig.tight_layout(); fig.savefig(FIG / f"08_forecast_{tag}.png", dpi=140); plt.close(fig)

    for f2 in st.folds:
        m2 = st.metrics(f2)
        p = m2[m2.level.isin(LEVELS)].pivot_table(index="model", columns="level", values="WAPE")[LEVELS] * 100
        keep = [x for x in ["snaive", "lgbm", "lgbm_bottom_up", sel[f2]] if x in p.index]
        fig, ax = plt.subplots(figsize=(8, 4)); w = 0.8 / len(keep)
        for i, mod in enumerate(dict.fromkeys(keep)):
            ax.bar(np.arange(5) + i * w, p.loc[mod], w, label=LBL(mod))
        ax.set_xticks(np.arange(5) + w); ax.set_xticklabels(["Total", "Group", "Store", "Dept", "Store x Dept"])
        ax.set_ylabel("WAPE %"); ax.legend(fontsize=7); ax.set_title(f"WAPE by hierarchy level ({f2} fold)")
        fig.tight_layout(); fig.savefig(FIG / f"09_levels_{f2}.png", dpi=140); plt.close(fig)
    print("report written")


if __name__ == "__main__":
    main()
